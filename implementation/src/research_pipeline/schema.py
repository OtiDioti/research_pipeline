# A fixed two-entry registry: DDL, allowed kinds, corresponding backup format.
_VERSIONS = MappingProxyType({1: (_SCHEMA_V1, _LEGACY_KINDS, 1),
                              2: (_SCHEMA_V2, _KINDS, 2)})


class ManifestLayoutError(ValueError):
    """A manifest has unsupported fields, versions or inventory ordering."""


def validate_schema(version, statements):
    """Check exact whitespace-normalized DDL and object count; return the version."""
    if type(version) is not int or version not in _VERSIONS:
        raise ValueError(f"unsupported or uninitialized schema version {version!r}")
    expected = _VERSIONS[version][0]
    if (len(statements) != len(expected)
            or {" ".join(sql.split()) for sql in statements} != {" ".join(sql.split()) for sql in expected}):
        raise ValueError(f"incomplete or malformed version-{version} schema")
    return version


def validate_request_kinds(request, version):
    """Reject kinds or declarations unavailable in this schema before new-request effects."""
    supported = _VERSIONS[version][1]
    for record in request.records:
        kinds = [record.kind, *(ref.target_kind for ref in record.record_references if ref.target_kind is not None)]
        for kind in kinds:
            if kind not in supported:
                raise DomainValidationError(f"kind {kind!r} is unsupported in schema {version}; migration is required")


def _pairs(pairs):
    """Decode JSON objects without accepting duplicate keys at any depth."""
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON key {key!r}")
        result[key] = value
    return result


def _constant(value):
    """Reject nonfinite JSON constants rather than Python's permissive decoding."""
    raise ValueError(f"nonfinite JSON number {value}")


def _json(data):
    """Parse strict UTF-8 JSON, including nested duplicates and nonfinite values."""
    if isinstance(data, bytes):
        data = data.decode("utf-8")
    value = json.loads(data, object_pairs_hook=_pairs, parse_constant=_constant)
    _validate_json(value, "JSON", set())
    return value


def _canonical(document):
    """Serialize a document using the existing strict canonical request convention."""
    return _snapshot(document, "backup document").encode("utf-8")


def manifest_info(document):
    """Return canonical identity, versions and references for either exact manifest pair."""
    if type(document) is not dict or set(document) != {"format_version", "schema_version", "metadata", "artifacts"}:
        raise ManifestLayoutError("manifest: incorrect fields")
    version = document["schema_version"]
    format_version = document["format_version"]
    if (type(version) is not int or type(format_version) is not int
            or version not in _VERSIONS or format_version != _VERSIONS[version][2]):
        raise ManifestLayoutError(f"manifest: unsupported format/schema pair ({format_version!r}, {version!r})")
    metadata = ArtifactReference.from_dict(document["metadata"])
    if type(document["artifacts"]) is not list:
        raise ManifestLayoutError("manifest artifacts: expected list")
    artifacts = tuple(ArtifactReference.from_dict(item) for item in document["artifacts"])
    digests = [item.digest for item in artifacts]
    if digests != sorted(set(digests)):
        raise ManifestLayoutError("manifest artifacts: require digest-sorted unique entries")
    return hashlib.sha256(_canonical(document)).hexdigest(), format_version, version, metadata, artifacts


def validate_history(rows, registrations):
    """Validate zero/one administrative transition against canonical source and current artifacts.

    This establishes internal consistency, not authentication of a hostile owner.
    Inputs are detached SQLite rows and artifact registrations; no data is rewritten.
    """
    if len(rows) > 1:
        raise ValueError("migration history: expected zero or one row")
    for migration_id, source, target, backup_id, manifest_text, provenance_text in rows:
        if any(type(value) is not int for value in (migration_id, source, target)) or (migration_id, source, target) != (1, 1, 2):
            raise ValueError("migration history: invalid singleton or schema transition")
        ArtifactReference(backup_id, 0)
        manifest = _json(manifest_text)
        identity, format_version, schema_version, _, artifacts = manifest_info(manifest)
        if ((format_version, schema_version) != (1, 1) or identity != backup_id
                or _canonical(manifest).decode() != manifest_text):
            raise ValueError("migration history: noncanonical legacy manifest or source identity mismatch")
        provenance = _json(provenance_text)
        if type(provenance) is not dict or set(provenance) != {"actor", "created_at", "details"}:
            raise ValueError("migration history: complete explicit provenance required")
        if _canonical(CreationProvenance.from_dict(provenance).to_dict()).decode() != provenance_text:
            raise ValueError("migration history: noncanonical provenance or timestamp")
        current = dict(registrations)
        if any(current.get(item.digest) != item.size for item in artifacts):
            raise ValueError("migration history: source artifact registration differs")
