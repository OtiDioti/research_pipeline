"""Execute the exact product/stdlib-only detached rendering guide from candidate-local source."""

from pathlib import Path
import subprocess
import sys
import unittest
from tests.test_vault import child_environment


class LifecycleRenderingExampleTests(unittest.TestCase):
    """The documented genuine capture/close/render path must execute its substantive assertions."""

    def test_exact_documented_example(self):
        """Run empty and delayed-cancelled sources, saved continuation, exact facts and closed gates."""
        root = Path(__file__).resolve().parents[2]
        document = (root/'docs/lifecycle-report-rendering.md').read_text()
        program = document.split('## Runnable detached rendering example\n', 1)[1].split('```python\n', 1)[1].split('```', 1)[0]
        self.assertNotIn('from tests', program)
        self.assertNotIn('import tests', program)
        result = subprocess.run([sys.executable, '-B', '-c', program], cwd=root,
            env=child_environment(), capture_output=True, text=True, timeout=180)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn('Detached empty and delayed cancelled sources rendered; exact saved continuation retained.', result.stdout)
        self.assertIn('Generated bytes only: no written files, publication, acknowledgment or authorization.', result.stdout)
